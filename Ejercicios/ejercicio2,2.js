let a = 10;
let b = 5;

console.log("Igualdad:", a == b);
console.log("Igualdad estricta:", a === b);
console.log("Diferente:", a != b);
console.log("Diferente estricto:", a !== b);
console.log("Mayor que:", a > b);
console.log("Menor que:", a < b);
console.log("Mayor o igual:", a >= b);
console.log("Menor o igual:", a <= b);

// Comparación entre número y texto
console.log(5 == "5");  
console.log(5 === "5");

// Explicación:
// == compara los valores y permite convertir tipos.
// === compara tanto el valor como el tipo de dato.