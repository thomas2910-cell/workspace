// Declaramos una variable con let
let producto = "Computador";

console.log(producto);

producto = "Celular";
console.log(producto);

producto = "Tablet";
console.log(producto);

// Declaramos una constante
const pais = "Colombia";

console.log(pais);

// Intentar cambiar una constante produce un error.
// pais = "México";

// Observación:
// Las variables let permiten cambiar su valor.
// Las constantes const no permiten reasignar su valor.