let precio = "350";

// Convertimos el texto a número
let precioNumero = Number(precio);

console.log("Precio convertido a número:", precioNumero);

// Sumamos 100
let resultado = precioNumero + 100;

console.log("Resultado de la suma:", resultado);

// Convertimos el resultado a texto
let resultadoTexto = String(resultado);

// Concatenamos el texto
let mensaje = resultadoTexto + " pesos colombianos";

console.log("Resultado final:", mensaje);